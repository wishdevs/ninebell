// 이미지는 public/manual-assets/<doc-id>/ 에 두고 /manual-assets/... 로 참조한다.
//
// ✍ 문체 원칙(2026-08-13) — 설명문이 아니라 **매뉴얼**이다. 액션이 주인공이다.
//
//   1. 한 문단 = 사용자가 하는 행동 하나. 동사로 끝낸다("…을 누릅니다", "…을 입력합니다").
//   2. 시스템 자동 처리는 그 행동의 **결과**로 붙인다: "실행을 누릅니다. → 저장까지 자동 처리됩니다."
//      행동 없이 시스템 상태만 말하는 문단은 쓰지 않는다. 꼭 필요하면 한 줄로 합친다.
//   3. 화면에 그냥 보이는 것(표시·배치·색)은 적지 않는다. 사용자의 다음 행동이 달라질 때만 적는다.
//   4. 아래는 쓰지 않는다: 배경·이유("…이기 때문에"), 감상("편리합니다"), 말 걸기("차근차근"),
//      필드 표가 이미 말한 내용의 산문 반복.
//   5. intro 는 "이 에이전트가 무엇을 처리하는가" 한 문장.
//   6. ⚠ 경고(실저장·상신)와 상신 핸드오프 안내는 짧게 쓰되 지우지 않는다 — 안전 문구다.

